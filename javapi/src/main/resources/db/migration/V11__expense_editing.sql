-- Defaults backfill existing rows and preserve inserts from older application versions.
ALTER TABLE public.expense
    ADD COLUMN category_source varchar(16) NOT NULL DEFAULT 'RULE',
    ADD COLUMN source varchar(16) NOT NULL DEFAULT 'EXTRACTED';

CREATE TABLE public.expense_category_change (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id bigint NOT NULL REFERENCES public.expense(id) ON DELETE CASCADE,
    report_id varchar(32) NOT NULL REFERENCES public.expense_report(id) ON DELETE CASCADE,
    app_user_id bigint NOT NULL REFERENCES public.app_user(id) ON DELETE CASCADE,
    old_category varchar,
    new_category varchar NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Re-editing appends history; deliberately no unique key on report/expense/name.
CREATE INDEX idx_expense_category_change_expense ON public.expense_category_change(expense_id);
CREATE INDEX idx_expense_category_change_report ON public.expense_category_change(report_id);
CREATE INDEX idx_expense_category_change_user ON public.expense_category_change(app_user_id);
